export type MessageKey = keyof (typeof MESSAGES)['en'];

/** Locales whose script runs right-to-left. */
export const RTL_LOCALES: ReadonlySet<Locale> = new Set<Locale>(['ar']);

export function isRtl(locale: Locale): boolean {
  return RTL_LOCALES.has(locale);
}

/**
 * The message key for an API error code, or null when the code has no catalog
 * entry — so a UI never falls back to rendering a raw `error.some_code` string.
 */
export function errorMessageKey(code: string): MessageKey | null {
  const key = `error.${code}`;
  return Object.prototype.hasOwnProperty.call(MESSAGES.en, key) ? (key as MessageKey) : null;
}

export function t(locale: Locale, key: MessageKey, params?: Record<string, string | number>): string {
  const catalog = MESSAGES[locale] ?? MESSAGES.en;
  const fallback = MESSAGES.en;
  const template: string = (catalog as Record<string, string>)[key] ?? (fallback as Record<string, string>)[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : whole,
  );
}

/** Verifies that every locale defines exactly the same key set. Used by a unit test. */
export function missingTranslationKeys(): Record<Locale, string[]> {
  const enKeys = new Set(Object.keys(MESSAGES.en));
  const result = {} as Record<Locale, string[]>;
  for (const locale of Object.keys(MESSAGES) as Locale[]) {
    const keys = new Set(Object.keys(MESSAGES[locale]));
    result[locale] = [...enKeys].filter((k) => !keys.has(k)).concat([...keys].filter((k) => !enKeys.has(k)));
  }
  return result;
}
