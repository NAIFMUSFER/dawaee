import type {
  AuditAction, CalendarSystem, CaregiverNotifyMode, CaregiverPermission, CaregiverRelationshipStatus,
  CaregiverRole, ConfirmationMethod, ConsentType, DeliveryStatus, DoseEventType, DoseStatus, DoseUnit,
  FoodInstruction, Locale, MeasurementType, MedicationForm, MedicationStatus, NotificationChannel,
  NotificationKind, NumeralSystem, ScheduleRuleKind, StrengthUnit, SymptomTag, TravelPolicy,
} from './enums.js';

export type UUID = string;
/** ISO-8601 instant in UTC, e.g. 2026-09-02T17:00:00.000Z */
export type Instant = string;
/** Calendar date with no time component, e.g. 2026-09-02 */
export type LocalDate = string;
/** Wall-clock time of day, HH:mm (24h) */
export type LocalTime = string;
/** IANA timezone identifier, e.g. Asia/Riyadh */
export type TimeZone = string;

// ---------------------------------------------------------------- accounts

export interface User {
  id: UUID;
  phoneE164: string | null;
  email: string | null;
  displayName: string;
  locale: Locale;
  timezone: TimeZone;
  createdAt: Instant;
  disabledAt: Instant | null;
}

/**
 * A person whose medication is being managed. One account may own several
 * (e.g. the user plus their father and mother). Medical data never crosses
 * profile boundaries.
 */
export interface PatientProfile {
  id: UUID;
  ownerUserId: UUID;
  /** Set when this profile belongs to a user who signed in themselves. */
  linkedUserId: UUID | null;
  displayName: string;
  birthYear: number | null;
  avatarKey: string | null;
  timezone: TimeZone;
  /** Timezone the schedules were authored in; used by travel mode. */
  homeTimezone: TimeZone;
  travelPolicy: TravelPolicy;
  isSelf: boolean;
  createdAt: Instant;
  archivedAt: Instant | null;
}

