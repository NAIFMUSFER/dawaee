// ---------------------------------------------------------------- schedules

export interface FixedTimesRule {
  kind: 'fixed_times';
  /** Wall-clock times in the schedule timezone. */
  times: LocalTime[];
}

export interface IntervalRule {
  kind: 'interval';
  everyHours: number;
  /** First dose time of the day, wall clock. */
  anchorTime: LocalTime;
  /** Optional window outside of which no dose is generated (sleep protection). */
  activeFrom?: LocalTime;
  activeUntil?: LocalTime;
}

export interface DaysOfWeekRule {
  kind: 'days_of_week';
  /** 0 = Sunday … 6 = Saturday (Saudi week starts Sunday). */
  weekdays: number[];
  times: LocalTime[];
}

export interface CycleRule {
  kind: 'cycle';
  daysOn: number;
  daysOff: number;
  times: LocalTime[];
  /** Day 1 of the first "on" block. */
  cycleAnchorDate: LocalDate;
}

export interface AsNeededRule {
  kind: 'as_needed';
  maxPerDay?: number;
  minHoursBetween?: number;
}

export type ScheduleRule = FixedTimesRule | IntervalRule | DaysOfWeekRule | CycleRule | AsNeededRule;

export interface MedicationSchedule {
  id: UUID;
  medicationId: UUID;
  patientProfileId: UUID;
  rule: ScheduleRule;
  ruleKind: ScheduleRuleKind;
  doseQuantity: number;
  doseUnit: DoseUnit;
  /** Timezone the wall-clock times are interpreted in. */
  timezone: TimeZone;
  startDate: LocalDate;
  endDate: LocalDate | null;
  /** Minutes after the scheduled time before the dose counts as missed. */
  missedAfterMinutes: number;
  /** Minutes after the scheduled time still counted as "taken late". */
  lateAfterMinutes: number;
  active: boolean;
  createdBy: UUID;
  createdAt: Instant;
  updatedAt: Instant;
}

